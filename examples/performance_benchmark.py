"""Reference-platform timing for the vectorised certification primitives.

The numbers are engineering diagnostics rather than detector latency claims.
They are intentionally generated by the same public API used by the examples.
"""

from __future__ import annotations

import json
import platform
import statistics
import sys
import time
from pathlib import Path

import numpy as np

from ratecert import (
    FixedPointSpec,
    RateQuantizationSpec,
    certify_acceptance,
    certify_rate,
    quantize_scores,
)


ROOT = Path(__file__).resolve().parents[1]


def _measure(function, repeats: int) -> dict[str, float | int]:
    samples_ms: list[float] = []
    for _ in range(repeats):
        start = time.perf_counter()
        function()
        samples_ms.append((time.perf_counter() - start) * 1000.0)
    return {
        "repeats": repeats,
        "median_ms": float(statistics.median(samples_ms)),
        "min_ms": float(min(samples_ms)),
        "max_ms": float(max(samples_ms)),
    }


def run(*, n_events: int = 100_000, repeats: int = 20, seed: int = 123) -> dict:
    rng = np.random.default_rng(seed)
    # Keep all values inside the declared unsigned 12-bit, 12-fractional-bit
    # range so the timing measures the normal path rather than saturation.
    scores = rng.random(n_events) * 0.9
    score_spec = FixedPointSpec(bits=12, fractional_bits=12)
    rate_spec = RateQuantizationSpec(lsb_hz=0.01, counter_bits=16)
    return {
        "study": "RateCert-HEP reference-platform primitive timing",
        "n_events": n_events,
        "repeats": repeats,
        "seed": seed,
        "python": sys.version.split()[0],
        "platform": platform.platform(),
        "measurements": {
            "quantize_scores": _measure(
                lambda: quantize_scores(scores, score_spec), repeats
            ),
            "certify_acceptance": _measure(
                lambda: certify_acceptance(
                    scores,
                    threshold_code=3500,
                    target_acceptance=0.1,
                    alpha=0.01,
                    spec=score_spec,
                    deployment_block_id="perf-deployment",
                    calibration_block_id="perf-calibration",
                ),
                repeats,
            ),
            "certify_rate": _measure(
                lambda: certify_rate(
                    scores,
                    exposure_s=100.0,
                    threshold_code=3500,
                    rate_budget_hz=12.0,
                    alpha=0.01,
                    spec=score_spec,
                    rate_spec=rate_spec,
                    deployment_block_id="perf-deployment",
                    calibration_block_id="perf-calibration",
                ),
                repeats,
            ),
        },
    }


def main() -> int:
    report = run()
    output = ROOT / "reports" / "performance_benchmark.json"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
